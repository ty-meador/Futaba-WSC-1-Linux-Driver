#!./.venv/bin/python
"""Cleans up build and packaging artifacts."""

from argparse import ArgumentParser
import typing as t
from pathlib import Path
import shutil
import sys

from __config__ import BUILD_DIR, NUITKA_OUTPUT_DIR, PACKAGE_DIR, WRAPPER_SCRIPT, LOGS_DIR, PROJECT_ROOT

parser = ArgumentParser()
parser.add_argument("--build", action="store_true", help="Remove previous build artifacts")
parser.add_argument("--package", action="store_true", help="Remove previous package artifacts")
parser.add_argument(
    "--empty-log-dir", action="store_true", help="Remove everything inside src/Futaba/logs"
)
ARGS = parser.parse_args()


def cleanLogsDir():
    """Remove any log files from the driver package."""
    for item in LOGS_DIR.iterdir():
        try:
            if item.is_file() or item.is_symlink():
                item.unlink()
            if item.is_dir():
                shutil.rmtree(item)
        except Exception as e:
            print(f"⚠️  WARNING: Unable to remove {item}")
            print(e)
            print(f"⚠️  WARNING: Unable to remove {item}")


def cleanBuildArtifacts():
    """Remove any artifacts generated by the build script."""
    for artifact in [
        BUILD_DIR,
        NUITKA_OUTPUT_DIR,
        WRAPPER_SCRIPT,
        PROJECT_ROOT / "compilation-report.xml",
    ]:
        try:
            if artifact.is_file():
                artifact.unlink()
            elif artifact.is_dir():
                shutil.rmtree(artifact)
        except Exception as e:
            print(f"⚠️  WARNING: Unable to remove {artifact}")
            print(e)
            print(f"⚠️  WARNING: Unable to remove {artifact}")

    for path in Path('.').rglob("*.egg-info"):
        shutil.rmtree(path, ignore_errors=True)


def cleanPackageArtifacts():
    """Remove any artifacts generated by the package script."""
    if PACKAGE_DIR.is_dir():
        shutil.rmtree(PACKAGE_DIR, ignore_errors=True)


def cleanPycache():
    """Find and remove all pycache folders in the project."""
    for path in Path('.').rglob("__pycache__"):
        shutil.rmtree(path, ignore_errors=True)


def cleanAll():
    """Remove all previously generated artifacts."""
    cleanLogsDir()
    cleanBuildArtifacts()
    cleanPackageArtifacts()
    cleanPycache()


if __name__ == "__main__":
    # If there were no arguments passed (except the script name, which is always passed)
    # assume that we need to clean *everything*
    if len(sys.argv) - 1 == 0:
        cleanAll()
    if ARGS.build:
        cleanBuildArtifacts()
    if ARGS.package:
        cleanPackageArtifacts()
    if ARGS.empty_log_dir:
        cleanLogsDir()
    if ARGS.pycache:
        cleanPycache()

    print("🧹 Removing previous artifacts...")
    print("✨ Done!")
