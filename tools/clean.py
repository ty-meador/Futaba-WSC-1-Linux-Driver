#!./.venv/bin/python
"""Cleans up build and packaging artifacts."""

import shutil
import sys
from argparse import ArgumentParser
from pathlib import Path

from __config__ import (
    BUILD_DIR,
    DOCS_DIR,
    LOGS_DIR,
    NUITKA_OUTPUT_DIR,
    PACKAGE_DIR,
    PROJECT_ROOT,
    WRAPPER_SCRIPT,
)


def _unlink(path: Path) -> bool:
    """Attempt to remove the given artifact with safe degredation.

    Args:
        artifact (Path): The path of the item you want removed

    Returns:
        bool: True if the items is successfully removed, false otherwise
    """
    try:
        if path.is_file():
            path.unlink()
        elif path.is_dir():
            shutil.rmtree(path)
    except Exception as e:
        print(f"WARNING: Unable to remove {path}")
        print(e)
        print(f"WARNING: Unable to remove {path}")
        return False
    return True


def cleanDocs():
    """Remove previously generated documenation artifacts."""
    for artifact in (DOCS_DIR / "build").iterdir():
        _unlink(artifact)


def cleanLogsDir():
    """Remove any log files from the driver package."""
    for artifact in LOGS_DIR.iterdir():
        _unlink(artifact)


def cleanBuildArtifacts():
    """Remove any artifacts generated by the build script."""
    for artifact in [
        BUILD_DIR,
        NUITKA_OUTPUT_DIR,
        WRAPPER_SCRIPT,
        PROJECT_ROOT / "compilation-report.xml",
    ]:
        _unlink(artifact)
    for path in Path(".").rglob("*.egg-info"):
        _unlink(path)


def cleanPackageArtifacts():
    """Remove any artifacts generated by the package script."""
    if PACKAGE_DIR.is_dir():
        _unlink(PACKAGE_DIR)


def cleanPycache():
    """Find and remove all pycache folders in the project."""
    for path in Path(".").rglob("__pycache__"):
        _unlink(path)


def cleanAll():
    """Remove all previously generated artifacts."""
    cleanDocs()
    cleanLogsDir()
    cleanBuildArtifacts()
    cleanPackageArtifacts()
    cleanPycache()


if __name__ == "__main__":
    parser = ArgumentParser()
    parser.add_argument(
        "--build", action="store_true", help="Remove previous build artifacts"
    )
    parser.add_argument(
        "--docs", action="store_true", help="Remove previous documentation artifacts"
    )
    parser.add_argument(
        "--package", action="store_true", help="Remove previous package artifacts"
    )
    parser.add_argument(
        "--empty-log-dir",
        action="store_true",
        help="Remove everything inside src/Futaba/logs",
    )
    parser.add_argument("--pycache", action="store_true", help="Clean up pycache files")
    ARGS = parser.parse_args()
    # If there were no arguments passed (except the script name, which is always passed)
    # assume that we need to clean *everything*
    if len(sys.argv) - 1 == 0:
        cleanAll()
    if ARGS.build:
        cleanBuildArtifacts()
    if ARGS.docs:
        cleanDocs()
    if ARGS.package:
        cleanPackageArtifacts()
    if ARGS.empty_log_dir:
        cleanLogsDir()
    if ARGS.pycache:
        cleanPycache()

    print("Removing previous artifacts...")
    print("Done!")
