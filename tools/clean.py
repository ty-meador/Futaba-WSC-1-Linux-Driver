#!./.venv/bin/python
"""Cleans up build and packaging artifacts."""

import shutil
import sys
from argparse import ArgumentParser

from util import BUILD_DIR, NUITKA_OUTPUT_DIR, PACKAGE_DIR, PROJECT_ROOT, PYPROJECT, WRAPPER_SCRIPT

# Refuse to run if we aren't operating in a venv
if sys.prefix == sys.base_prefix:
    if not (PROJECT_ROOT / ".venv").exists():
        print("Script must be run from a venv. Try the following first.")
        print(f"NOTE: Python version requirement -> {PYPROJECT['project']['requires-python']}")
        print("python3 -m venv venv")
    else:
        print(
            f"You appear to have a virtual environment setup in {PROJECT_ROOT / '.venv'} "
            "but it is not active. Try: source .venv/bin/activate"
        )
    sys.exit(1)


parser = ArgumentParser()


parser = ArgumentParser()
parser.add_argument("--build", action="store_true", help="Remove previous build artifacts")
parser.add_argument("--package", action="store_true", help="Remove previous package artifacts")


def cleanBuildArtifacts():
    """Remove previous build artifacts."""
    for dep in [BUILD_DIR, NUITKA_OUTPUT_DIR, WRAPPER_SCRIPT]:
        try:
            if dep.is_file():
                dep.unlink()
            elif dep.is_dir():
                shutil.rmtree(dep)
        except Exception as e:
            print(f"⚠️  WARNING: Unable to remove {dep}")
            print(e)
            print(f"⚠️  WARNING: Unable to remove {dep}")


def cleanPackageArtifacts():
    """Remove any artifacts generated by this script."""
    if PACKAGE_DIR.is_dir():
        shutil.rmtree(PACKAGE_DIR)


if __name__ == "__main__":
    args = parser.parse_args()

    if args.build:
        print("🧹 Removing previous build artifacts...")
        cleanBuildArtifacts()
    elif args.package:
        print("🧹 Removing previous package artifacts...")
        cleanPackageArtifacts()
    else:
        print("🧹 Removing previous artifacts...")
        cleanBuildArtifacts()
        cleanPackageArtifacts()
    print("✨ Done!")
